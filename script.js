const buildBriefText = () => {
  const name = getTrimmedValue(byId("brief-name"));
  const company = getTrimmedValue(byId("brief-company"));
  const message = getTrimmedValue(byId("brief-message"));

  const lines = [
    "Olá, Matheus!",
    "",
    `Meu nome é ${name || "Não informado"},`,
    "",
    `trabalho na empresa ${company || "Não informada"}`,
    "",
    `e tenho a seguinte necessidade: ${message || "Não informada"}`,
    "",
    "Aguardo retorno para alinharmos o projeto."
  ];

  return {
    subject: company
      ? `Projeto de sistema - ${company}`
      : siteConfig.contact.defaultSubject,
    body: lines.join("\n"),
    isComplete: Boolean(name && company && message)
  };
};

const briefStatus = byId("brief-status");
const briefForm = byId("brief-form");
const briefNameInput = byId("brief-name");
const briefCompanyInput = byId("brief-company");
const briefMessageInput = byId("brief-message");
const briefWhatsappButton = byId("brief-whatsapp");
const briefEmailButton = byId("brief-email");

const updateBriefStatus = (text) => {
  if (briefStatus) briefStatus.textContent = text;
};

const setButtonEnabledState = (button, isEnabled) => {
  if (!button) return;

  button.disabled = !isEnabled;

  if (isEnabled) {
    button.removeAttribute("disabled");
    return;
  }

  button.setAttribute("disabled", "");
};

const syncBriefState = () => {
  const brief = buildBriefText();

  setButtonEnabledState(briefWhatsappButton, brief.isComplete);
  setButtonEnabledState(briefEmailButton, brief.isComplete);

  updateBriefStatus(
    brief.isComplete
      ? "Briefing pronto para envio."
      : "Preencha nome, empresa e necessidade para liberar o envio."
  );
};

const openBriefChannel = (channel) => {
  const brief = buildBriefText();

  if (!brief.isComplete) {
    updateBriefStatus("Preencha nome, empresa e necessidade para liberar o envio.");

    if (!getTrimmedValue(briefNameInput)) {
      briefNameInput?.focus();
      return;
    }

    if (!getTrimmedValue(briefCompanyInput)) {
      briefCompanyInput?.focus();
      return;
    }

    briefMessageInput?.focus();
    return;
  }

  updateBriefStatus("");

  const url =
    channel === "whatsapp"
      ? buildWhatsAppUrl(brief.body)
      : buildGmailUrl(brief.subject, brief.body);

  window.location.assign(url);
};

briefWhatsappButton?.addEventListener("click", () => openBriefChannel("whatsapp"));
briefEmailButton?.addEventListener("click", () => openBriefChannel("email"));

briefForm?.addEventListener("input", syncBriefState);
briefForm?.addEventListener("change", syncBriefState);
briefNameInput?.addEventListener("keyup", syncBriefState);
briefCompanyInput?.addEventListener("keyup", syncBriefState);
briefMessageInput?.addEventListener("keyup", syncBriefState);

syncBriefState();

const syncHeaderHeight = () => {
  if (!siteHeader) return;

  const height = Math.ceil(siteHeader.getBoundingClientRect().height);
  document.documentElement.style.setProperty("--header-height", `${height}px`);
};

const updateNavIndicator = (animate = true) => {
  if (!mainNav || !navIndicator || !navLinks.length) return;

  const activeLink = mainNav.querySelector("a.is-active") || navLinks[0];
  if (!activeLink) return;

  const navRect = mainNav.getBoundingClientRect();
  const linkRect = activeLink.getBoundingClientRect();

  navIndicator.style.setProperty("--indicator-x", `${linkRect.left - navRect.left}px`);
  navIndicator.style.setProperty("--indicator-y", `${linkRect.top - navRect.top}px`);
  navIndicator.style.setProperty("--indicator-width", `${linkRect.width}px`);
  navIndicator.style.setProperty("--indicator-height", `${linkRect.height}px`);

  if (!mainNav.classList.contains("is-ready")) {
    mainNav.classList.add("is-ready");
    return;
  }

  if (!animate) return;

  mainNav.classList.add("is-moving");
  clearTimeout(navMotionTimeout);
  navMotionTimeout = window.setTimeout(() => {
    mainNav.classList.remove("is-moving");
  }, 560);
};

const setActiveNavigation = (activeHref, { animateIndicator = true } = {}) => {
  activeNavHref = activeHref;

  navLinks.forEach((link) => {
    const isActive = link.getAttribute("href") === activeHref;
    link.classList.toggle("is-active", isActive);

    if (isActive) {
      link.setAttribute("aria-current", "page");
      return;
    }

    link.removeAttribute("aria-current");
  });

  window.requestAnimationFrame(() => updateNavIndicator(animateIndicator));
};

const clearPendingNavigation = () => {
  pendingNavHref = "";
  clearTimeout(pendingNavTimeout);
};

const isPendingNavigationSettled = () => {
  if (!pendingNavHref) return true;

  const target = document.querySelector(pendingNavHref);
  if (!target) return true;

  const headerOffset = siteHeader?.offsetHeight || 0;
  return Math.abs(target.getBoundingClientRect().top - headerOffset) <= 42;
};

const holdClickedNavigation = (href) => {
  pendingNavHref = href;
  clearTimeout(pendingNavTimeout);
  pendingNavTimeout = window.setTimeout(clearPendingNavigation, 900);
};

const syncActiveNavigation = ({ forceIndicator = false, animateIndicator = true } = {}) => {
  if (!navLinks.length) return;

  if (!forceIndicator && pendingNavHref) {
    if (!isPendingNavigationSettled()) return;
    clearPendingNavigation();
  }

  const threshold = window.scrollY + (siteHeader?.offsetHeight || 0) + 32;
  let activeHref = "#top";

  navLinks.forEach((link) => {
    const href = link.getAttribute("href");
    const target = href ? document.querySelector(href) : null;

    if (!target) return;

    if (threshold >= target.offsetTop) {
      activeHref = href;
    }
  });

  if (!forceIndicator && activeHref === activeNavHref) return;

  setActiveNavigation(activeHref, { animateIndicator });
};

const syncHeaderNavigation = (animateIndicator = false) => {
  syncHeaderHeight();
  syncActiveNavigation({ forceIndicator: true, animateIndicator });
};

window.addEventListener("resize", syncHeaderNavigation);
window.addEventListener("scroll", syncActiveNavigation, { passive: true });
window.addEventListener("hashchange", () => {
  const href = window.location.hash || "#top";

  if (navLinks.some((link) => link.getAttribute("href") === href)) {
    holdClickedNavigation(href);
    setActiveNavigation(href, { animateIndicator: true });
    return;
  }

  syncHeaderNavigation(true);
});

navLinks.forEach((link) => {
  link.addEventListener("click", () => {
    const href = link.getAttribute("href");
    if (!href) return;
    holdClickedNavigation(href);
    setActiveNavigation(href, { animateIndicator: true });
  });
});

const revealElements = document.querySelectorAll("[data-reveal]");

revealElements.forEach((element, index) => {
  const siblingIndex = [...element.parentElement.children].filter((child) =>
    child.hasAttribute("data-reveal")
  ).indexOf(element);
  const delayIndex = siblingIndex >= 0 ? siblingIndex : index;

  element.style.setProperty("--reveal-delay", `${Math.min(delayIndex, 5) * 80}ms`);
});

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.18 }
);

const revealVisibleElements = () => {
  revealElements.forEach((element) => {
    const rect = element.getBoundingClientRect();

    if (rect.top <= window.innerHeight * 0.92) {
      element.classList.add("is-visible");
      return;
    }

    revealObserver.observe(element);
  });
};

window.addEventListener("load", revealVisibleElements, { once: true });
window.addEventListener("load", () => syncHeaderNavigation(false), { once: true });
